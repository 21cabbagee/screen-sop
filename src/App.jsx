import React, { useState } from 'react';
import Header from './components/Header';
import Hero from './components/Hero';
import ScreenCaptureStudio from './components/ScreenCaptureStudio';
import KeyframeTimeline from './components/KeyframeTimeline';
import MarkdownExportDeck from './components/MarkdownExportDeck';
import CabModal from './components/CabModal';
import Footer from './components/Footer';
import { PRESET_WORKFLOWS, GENERATED_MARKDOWN_SAMPLE } from './data/mockSopData';

export default function App() {
  const [currentWorkflow, setCurrentWorkflow] = useState(PRESET_WORKFLOWS[0]);
  const [steps, setSteps] = useState(PRESET_WORKFLOWS[0].steps);
  const [markdownContent, setMarkdownContent] = useState(GENERATED_MARKDOWN_SAMPLE);
  const [isCabOpen, setIsCabOpen] = useState(false);

  const handleSelectWorkflow = (wf) => {
    setCurrentWorkflow(wf);
    setSteps(wf.steps);
    generateMarkdownForWorkflow(wf, wf.steps);
  };

  const handleUpdateStep = (stepId, updatedData) => {
    const updatedSteps = steps.map(s => s.id === stepId ? { ...s, ...updatedData } : s);
    setSteps(updatedSteps);
    generateMarkdownForWorkflow(currentWorkflow, updatedSteps);
  };

  const generateMarkdownForWorkflow = (wf, currentSteps) => {
    let md = `# SOP: ${wf.title}\n\n`;
    md += `**Target Application:** ${wf.targetApp}  \n`;
    md += `**Author:** ${wf.author}  \n`;
    md += `**Generated By:** ScreenSOP AI Multimodal Vision Pipeline  \n`;
    md += `**Version:** 1.0 (Production Verified)\n\n---\n\n`;

    currentSteps.forEach((step) => {
      md += `### Step ${step.stepNumber}: ${step.title}\n`;
      md += `${step.instruction}\n\n`;
      if (step.callout) {
        md += `> **Operational Note:** ${step.callout}\n\n`;
      }
      md += `---\n\n`;
    });

    setMarkdownContent(md);
  };

  const handleSynthesizeWorkflow = (wf) => {
    generateMarkdownForWorkflow(wf, steps);
    document.getElementById('markdown-export')?.scrollIntoView({ behavior: 'smooth' });
  };

  const scrollToStudio = () => {
    document.getElementById('capture-studio')?.scrollIntoView({ behavior: 'smooth' });
  };

  const scrollToMarkdown = () => {
    document.getElementById('markdown-export')?.scrollIntoView({ behavior: 'smooth' });
  };

  return (
    <div className="min-h-screen bg-dark-950 text-slate-100 flex flex-col font-sans selection:bg-sop-500/30 selection:text-white">
      {/* Navigation Header */}
      <Header onOpenCab={() => setIsCabOpen(true)} />

      {/* Main Content */}
      <main className="flex-1">
        {/* Hero Section */}
        <Hero
          onJumpToStudio={scrollToStudio}
          onJumpToMarkdown={scrollToMarkdown}
        />

        {/* Screen Capture Studio */}
        <ScreenCaptureStudio
          currentWorkflow={currentWorkflow}
          onSelectWorkflow={handleSelectWorkflow}
          onSynthesizeWorkflow={handleSynthesizeWorkflow}
        />

        {/* Keyframe Sampling & Vision Instructions */}
        <KeyframeTimeline
          steps={steps}
          onUpdateStep={handleUpdateStep}
        />

        {/* 1-Click Markdown & Knowledge Base Export */}
        <MarkdownExportDeck
          markdownContent={markdownContent}
          workflowTitle={currentWorkflow.title}
        />
      </main>

      {/* Footer */}
      <Footer onOpenCab={() => setIsCabOpen(true)} />

      {/* CAB Modal */}
      <CabModal
        isOpen={isCabOpen}
        onClose={() => setIsCabOpen(false)}
      />
    </div>
  );
}
